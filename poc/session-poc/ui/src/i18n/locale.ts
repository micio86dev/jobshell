export const MESSAGES: Record<Locale, Record<MessageKey, string>> = { en: EN, it: IT };

/** The language a system tag names, if the app has messages for it; English otherwise. */
export const osLocale = (tag: string | undefined): Locale => {
  const language = (tag ?? '').toLowerCase().split(/[-_]/)[0] ?? '';
  return (LOCALES as readonly string[]).includes(language) ? (language as Locale) : 'en';
};

/** The navigation language: the primary language when the app has messages for it, else the system's. */
export const resolveLocale = (primary: string | null, system: string | undefined): Locale => {
  if (primary !== null && (LOCALES as readonly string[]).includes(primary)) return primary as Locale;
  return osLocale(system);
};

/** A message in a locale, with `{name}` parameters filled in. A missing key shows the key itself. */
export const translate = (
  locale: Locale,
  key: MessageKey,
  params: Record<string, string | number> = {},
): string => {
  const template = MESSAGES[locale][key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_match, name: string) => String(params[name] ?? `{${name}}`));
};
